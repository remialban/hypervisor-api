-- Short-lived tokens accepted by websockify. The token file is generated from this table.
CREATE TABLE vnc_tokens (
    token TEXT PRIMARY KEY,
    target TEXT NOT NULL,
    expires_at BIGINT NOT NULL
);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at BIGINT NOT NULL,
    user_id TEXT,
    username TEXT,
    action TEXT NOT NULL,
    target TEXT,
    detail TEXT,
    success BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX audit_log_by_time ON audit_log (at);

-- VM templates: an editable definition (Packer configuration, disk name, pool). Each build
-- is a version, in template_versions.
CREATE TABLE templates (
    id TEXT PRIMARY KEY,
    hypervisor_id TEXT NOT NULL REFERENCES hypervisors (id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    packer_config TEXT NOT NULL,
    -- File name of the disk image Packer writes (looked up in its output).
    disk_name TEXT NOT NULL,
    -- libvirt pool receiving the built disks.
    pool TEXT NOT NULL,
    -- Who may use it besides admins and the rights below: everyone granted its hypervisor,
    -- or only through rights.
    visibility TEXT NOT NULL DEFAULT 'hypervisor' CHECK (visibility IN ('hypervisor', 'restricted')),
    -- Whether VMs may be created from it.
    allow_vm_creation BOOLEAN NOT NULL DEFAULT TRUE,
    created_by TEXT REFERENCES users (id) ON DELETE SET NULL,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    UNIQUE (hypervisor_id, name)
);
CREATE INDEX templates_by_hypervisor ON templates (hypervisor_id);

-- Each build of a template: its own disk, state and log.
CREATE TABLE template_versions (
    template_id TEXT NOT NULL REFERENCES templates (id) ON DELETE CASCADE,
    version BIGINT NOT NULL,
    -- Snapshot of the definition this version is built from.
    packer_config TEXT NOT NULL,
    disk_name TEXT NOT NULL,
    pool TEXT NOT NULL,
    volume TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending', 'in_progress', 'stopping', 'created', 'failed', 'cancelled')),
    -- Virtual size of the built disk, once created: counted in the quota of each VM.
    disk_size_gb BIGINT,
    -- End of the build output when the build failed.
    error TEXT,
    -- Output of the build (Packer included), capped.
    log TEXT NOT NULL DEFAULT '',
    created_by TEXT REFERENCES users (id) ON DELETE SET NULL,
    created_at BIGINT NOT NULL,
    started_at BIGINT,
    finished_at BIGINT,
    PRIMARY KEY (template_id, version)
);
-- At most one build at a time per template.
CREATE UNIQUE INDEX template_versions_one_build ON template_versions (template_id)
    WHERE status IN ('pending', 'in_progress', 'stopping');

-- Groups of users, managed by admins. A group holds users and other groups (nested groups);
-- a user or a group can be in several groups. ("groups" is an SQL keyword: hence user_groups.)
CREATE TABLE user_groups (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX user_groups_name ON user_groups (lower(name));

CREATE TABLE user_group_members (
    group_id TEXT NOT NULL REFERENCES user_groups (id) ON DELETE CASCADE,
    user_id TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (group_id, user_id)
);
CREATE INDEX user_group_members_by_user ON user_group_members (user_id);

-- child_id is a member of group_id. The API refuses cycles (a group inside itself).
CREATE TABLE user_group_subgroups (
    group_id TEXT NOT NULL REFERENCES user_groups (id) ON DELETE CASCADE,
    child_id TEXT NOT NULL REFERENCES user_groups (id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (group_id, child_id),
    CHECK (group_id <> child_id)
);
CREATE INDEX user_group_subgroups_by_child ON user_group_subgroups (child_id);

-- Rights on a template, given to a user or to a group (and so to every user in it,
-- nested groups included). `use`: see it and create VMs from it; `manage`: also edit,
-- rebuild and stop it and read its logs. max_vms: how many VMs from this template each
-- user covered may own (NULL = no limit).
CREATE TABLE template_permissions (
    template_id TEXT NOT NULL REFERENCES templates (id) ON DELETE CASCADE,
    user_id TEXT REFERENCES users (id) ON DELETE CASCADE,
    group_id TEXT REFERENCES user_groups (id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('use', 'manage')),
    max_vms BIGINT CHECK (max_vms IS NULL OR max_vms >= 0),
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    CHECK ((user_id IS NULL) <> (group_id IS NULL))
);
CREATE UNIQUE INDEX template_permissions_by_user ON template_permissions (template_id, user_id)
    WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX template_permissions_by_group ON template_permissions (template_id, group_id)
    WHERE group_id IS NOT NULL;

-- Which template each VM was created from, to count it in the limits above. The row goes
-- with the VM's owner row (VM deleted) or with the template.
CREATE TABLE template_vms (
    hypervisor_id TEXT NOT NULL,
    vm_id TEXT NOT NULL,
    template_id TEXT NOT NULL REFERENCES templates (id) ON DELETE CASCADE,
    version BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (hypervisor_id, vm_id),
    FOREIGN KEY (hypervisor_id, vm_id) REFERENCES vm_owners (hypervisor_id, vm_id) ON DELETE CASCADE
);
CREATE INDEX template_vms_by_template ON template_vms (template_id);
